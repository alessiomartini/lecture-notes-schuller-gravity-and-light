"""Build the per-lecture transcripts and the video table.

Inputs (SOURCES below): materials/<csv>   n, kind, youtube, fautv, title, duration, lecturer (from the SOURCES inventory)
  materials/transcripts/raw/ or ../lecture-notes-schuller-courses/materials/raw/C3/NNN-<id>.<lang>[-orig].json3   YouTube captions (NNN = csv row number), or
  NNN-<id>.whisper.txt         local faster-whisper output ('seconds<TAB>text')
Outputs:
  materials/transcripts/CXX-VYY.txt             one line per ~20 s, '[m:ss] text' (C = chapter number, V = video in the chapter)
  lecture-notes/videos.tex                      \\tsvideo{C@V}{id} table read by the preamble (\\ts links)
Chapter numbering: csv row n -> chapter n + offset, video V1. Tutorial rows (kind 'tutorial') are extra videos of
the chapter of the preceding lecture (V2, V3, ...). Rows without a YouTube id are skipped (see CLAUDE.md).
Run: python -I -X utf8 tools/transcripts.py
"""
import csv, json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAT = ROOT / 'materials'
# own downloads first, then the shared download of the inventory repo (NNN = csv row number, 1-based)
RAWS = [MAT / 'transcripts/raw', ROOT.parent / 'lecture-notes-schuller-courses/materials/raw/C3']
LINE_SECONDS = 20
# (csv in materials/, chapter offset, caption language)
SOURCES = [('videos.csv', 0, 'en')]


def mmss(s):
    s = int(s)
    return f'{s // 3600}:{s // 60 % 60:02d}:{s % 60:02d}' if s >= 3600 else f'{s // 60}:{s % 60:02d}'


def words_json3(path):
    for ev in json.load(open(path, encoding='utf-8')).get('events', []):
        for seg in ev.get('segs', []):
            w = seg['utf8'].strip()
            if w:
                yield (ev['tStartMs'] + seg.get('tOffsetMs', 0)) / 1000, w


def words_whisper(path):
    for line in open(path, encoding='utf-8'):
        t, _, text = line.rstrip('\n').partition('\t')
        yield float(t), text


def lines(words):
    out, start, buf = [], None, []
    for t, w in words:
        start = t if start is None else start
        buf.append(w)
        if t - start >= LINE_SECONDS:
            out.append((start, ' '.join(buf)))
            start, buf = None, []
    if buf:
        out.append((start, ' '.join(buf)))
    return out


rows = []  # (chapter, video, lang, csv row, row number)
for name, offset, lang in SOURCES:
    ch, v = 0, 0
    for i, r in enumerate(csv.DictReader(open(MAT / name, encoding='utf-8')), 1):
        if r['kind'] == 'tutorial':
            v += 1
        else:
            ch, v = int(r['n']) + offset, 1
        rows.append((ch, v, lang, r, i))

with open(ROOT / 'lecture-notes/videos.tex', 'w', encoding='utf-8') as f:
    f.write('% Generated by tools/transcripts.py: YouTube ID of every video (chapter@video)\n')
    for ch, v, lang, r, i in rows:
        if r['youtube']:
            f.write(f"\\tsvideo{{{ch}@{v}}}{{{r['youtube']}}} % {r['title']}\n")

(MAT / 'transcripts').mkdir(parents=True, exist_ok=True)
done = []
for ch, v, lang, r, i in rows:
    vid = r['youtube']
    if not vid:
        continue
    src = words = None
    for raw in RAWS:
        src = next(iter(sorted(raw.glob(f'{i:03d}-{vid}.{lang}*.json3'))), None)
        if src:
            words = words_json3(src)
            break
        src = next(iter(raw.glob(f'{i:03d}-{vid}.whisper.txt')), None)
        if src:
            words = words_whisper(src)
            break
    if not src:
        continue
    out = MAT / f'transcripts/C{ch:02d}-V{v:02d}.txt'
    with open(out, 'w', encoding='utf-8') as f:
        f.write(f"Chapter {ch} video {v}: {r['title']} | https://youtu.be/{vid} | {r['duration']} | "
                f"lecturer: {r['lecturer']} | source: {src.name}\n")
        for t, text in lines(words):
            f.write(f'[{mmss(t)}] {text}\n')
    done.append(f'C{ch:02d}-V{v:02d}')
print(f'{len(rows)} videos in the csv files, transcripts for {done}')
