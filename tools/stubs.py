"""Create a stub chapter for every lecture/chapter that has no chapter file yet, and the \\part/\\include list in main.tex.

A stub has the chapter title, the Sources box (video link, length, transcript file) and an empty Reading box,
so the book always lists the whole course. Existing chapter files are never touched. Tutorial videos (kind
'tutorial' in the csv) become a stub section at the end of the chapter of the lecture they follow.
Chapter numbering as in tools/transcripts.py. Chapters without a video (papers, talks) are listed in EXTRA.
Run: python -I -X utf8 tools/stubs.py
"""
import csv, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LN = ROOT / 'lecture-notes'
# (csv in materials/, chapter offset)
SOURCES = [('videos.csv', 0)]
# English titles where the csv title is German or messy: chapter -> title
TITLES = {}
# chapters without a video: (chapter, title, source)
EXTRA = [(29, 'All spacetimes beyond Einstein (Obergurgl lectures)', 'arXiv:1111.4824'), (30, "How quantizable matter gravitates: a practitioner's guide", 'arXiv:1402.6548'), (31, 'Constructive gravity: foundations and applications (MG15 review)', 'arXiv:2003.09726'), (32, 'Constructive gravity talk, Causal Fermion Systems 2025', 'YouTube GE9wGmhRBe4'), (33, 'Theories of Everything interview, 2025', 'YouTube Bnh-UNrxYZg'), (34, 'Saarland 2021 talk: Die Struktur der Raumzeit', 'YouTube 2vef2GqLJ7M'), (35, 'PIRSA 2004: classical limit of quantum gravity in an accelerating universe', 'pirsa.org/04110037')]
# \part inserted before this chapter number
PARTS = {1: 'Gravity and Light', 29: 'Constructive gravity'}


def clean(title):
    t = re.sub(r'^(Lecture|Tutorial) \d+( & 10)?:\s*', '', title)
    t = re.sub(r'\s*\((International|Heraeus).*\)\s*$', '', t)
    t = re.sub(r'\s*-?\s*(Lec ?\d+|L ?\d+)\s*-?\s*Frederic.*$', '', t)
    return t.strip(' -')


def tx(s):
    return s.replace('&', '\\&').replace('_', '\\_').replace('#', '\\#')


def slug(t):
    return '-'.join(re.sub(r'[^a-z0-9 ]', ' ', t.lower()).split()[:4])


chapters = {}  # n -> dict(title, row, tutorials)
for name, offset in SOURCES:
    ch = 0
    for r in csv.DictReader(open(ROOT / 'materials' / name, encoding='utf-8')):
        if r['kind'] == 'tutorial':
            chapters[ch]['tutorials'].append(r)
        else:
            ch = int(r['n']) + offset
            chapters[ch] = dict(title=TITLES.get(ch, clean(r['title'])), row=r, tutorials=[], src=None)
for n, title, src in EXTRA:
    chapters[n] = dict(title=title, row=None, tutorials=[], src=src)

includes = []
for n in sorted(chapters):
    c = chapters[n]
    title, r = tx(c['title']), c['row']
    if n in PARTS:
        includes.append(f'\\part{{{PARTS[n]}}}')
    existing = sorted((LN / 'chapters').glob(f'ch{n:02d}-*.tex'))
    path = existing[0] if existing else LN / f'chapters/ch{n:02d}-{slug(c["title"])}.tex'
    includes.append(f'\\include{{chapters/{path.stem}}}')
    if existing:
        continue
    if r:
        vid = f"\\seg{{{n}}}{{1}}{{{title}}}" if r['youtube'] else tx(title)
        where = '' if r['youtube'] else f" (no YouTube id; FAU.tv: \\url{{{r['fautv']}}})"
        src = f"{vid} & {r['duration']} & (to be written){where}\\\\"
        tr = f"\\smallskip\n\\textbf{{Transcript}} \\file{{materials/transcripts/C{n:02d}-V01.txt}}.\n"
        lec = r['lecturer'].rstrip('?')
        note = ''
        if lec != 'Schuller':
            note = f"\\begin{{coursenote}}[Lecturer]\nLecturer: {lec}, not Schuller.\n\\end{{coursenote}}\n\n"
        secs = ''
        for k, t in enumerate(c['tutorials']):
            tn = t['n'][1:] + (' \\& 10' if t['n'] == 'T9' else '')
            link = f"\\seg{{{n}}}{{{k + 2}}}{{video}}" if t['youtube'] else 'sheet only, no video'
            secs += (f"\n\\section{{Tutorial {tn}}}\\label{{sec:t{n:02d}-{k + 1}}}\n"
                     f"Tutorial {tn}, {t['duration']}, {link}. (to be written; the sheet is paraphrased, never copied)\n")
    else:
        src = f"{tx(c['src'])} & -- & (to be written)\\\\"
        tr, note, secs = '', '', ''
    path.write_text(f"""% !TEX root = ../main.tex
% STUB: generated by tools/stubs.py; write the chapter from the source (transcript in materials/transcripts/ if any)
\\chapter{{{title}}}\\label{{ch:c{n:02d}}}
\\begin{{paracol}}{{2}}

\\begin{{sources}}
\\begin{{tabularx}}{{\\linewidth}}{{@{{}}l l L@{{}}}}
\\toprule
\\textbf{{Source}} & \\textbf{{Length}} & \\textbf{{Content}}\\\\
\\midrule
{src}
\\bottomrule
\\end{{tabularx}}

{tr}\\end{{sources}}

{note}\\begin{{reading}}[Where this chapter sits in the other notes]
(to be written)
\\end{{reading}}

\\emph{{This chapter has not been written yet.}}
{secs}
\\flushside
\\end{{paracol}}
""", encoding='utf-8')
    print('stub', path.name)

main = (LN / 'main.tex').read_text(encoding='utf-8')
block = '% BEGIN CHAPTERS (tools/stubs.py)\n' + '\n'.join(includes) + '\n% END CHAPTERS'
if '% BEGIN CHAPTERS' in main:
    main = re.sub(r'% BEGIN CHAPTERS.*?% END CHAPTERS', lambda m: block, main, flags=re.S)
else:
    main = main.replace('% (no lecture chapters yet)', block)
(LN / 'main.tex').write_text(main, encoding='utf-8')
print(len(includes), 'lines in main.tex block')
